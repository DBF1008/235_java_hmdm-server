package com.hmdm.rest.json;

import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import io.swagger.annotations.ApiModel;
import io.swagger.annotations.ApiModelProperty;

import java.io.Serializable;

/**
 * <p>Request body for completing a password reset (step 2: validate token and set new password).</p>
 */
@ApiModel(description = "Request to complete password reset")
@JsonIgnoreProperties(ignoreUnknown = true)
public class PasswordResetCompleteForm implements Serializable {

    private static final long serialVersionUID = 1L;

    @ApiModelProperty(value = "Password reset token received via email", required = true)
    private String token;

    @ApiModelProperty(value = "New password as MD5 hash", required = true)
    private String password;

    public PasswordResetCompleteForm() {
    }

    public String getToken() {
        return token;
    }

    public void setToken(String token) {
        this.token = token;
    }

    public String getPassword() {
        return password;
    }

    public void setPassword(String password) {
        this.password = password;
    }
}
